<?php
// Writes model/l18n/v2_labels.php: ['<Sci_Name>' => ['en' => ..., 'nl' => ...], ...]
// from labels_en.json and labels_nl.json, so v2 pages can include one small PHP array
// (opcache-friendly) instead of parsing two JSON files per request.
// Usage: php scripts/v2_make_labels.php [out_path]
$l18n = __DIR__ . '/../model/l18n';
$out = $argv[1] ?? $l18n . '/v2_labels.php';

$read = function (string $lang) use ($l18n): array {
    $raw = @file_get_contents("$l18n/labels_$lang.json");
    $data = $raw === false ? null : json_decode($raw, true);
    if (!is_array($data) || !$data) {
        fwrite(STDERR, "v2_make_labels: cannot read labels_$lang.json\n");
        exit(1);
    }
    return $data;
};
$en = $read('en');
$nl = $read('nl');

$labels = [];
foreach ($en as $sci => $name_en) {
    $labels[$sci] = ['en' => $name_en, 'nl' => $nl[$sci] ?? $name_en];
}
foreach ($nl as $sci => $name_nl) {
    $labels[$sci] ??= ['en' => $sci, 'nl' => $name_nl];
}
ksort($labels, SORT_STRING);

$php = "<?php\n// Generated by scripts/v2_make_labels.php. Do not edit.\nreturn " . var_export($labels, true) . ";\n";
$tmp = @tempnam(dirname($out), basename($out) . '.');
if ($tmp === false || file_put_contents($tmp, $php) !== strlen($php) || !chmod($tmp, 0644) || !rename($tmp, $out)) {
    if ($tmp !== false) @unlink($tmp);
    fwrite(STDERR, "v2_make_labels: cannot write $out\n");
    exit(1);
}
echo "v2_make_labels: wrote " . count($labels) . " species to $out\n";
